	/** @inheritDoc */
	override async _prepareContext(_options: ApplicationV2.RenderOptions): Promise<QuenchResultData> {
		const filterSetting = getFilterSetting();
		const preselected = this.quench._filterBatches(filterSetting, {
			preSelectedOnly: true,
		});
		return {
			anyBatches: this.quench._testBatches.size > 0,
			batches: this.quench._testBatches.map((batchData) => {
				return {
					name: batchData.key,
					displayName: batchData.displayName,
					selected: preselected.includes(batchData.key),
				};
			}),
		};
	}

	/** @inheritDoc */
	// biome-ignore lint/suspicious/useAwait: Do not change the function signature
	override async _onRender(context: QuenchResultData, options: ApplicationV2.RenderOptions) {
		super._onRender(context, options);
		this._resetFailureNavigation(true);
		this._hasFilteredRows = false;
		this._resultsRootElement = this.element.querySelector(":scope > .window-content");
		this._failureAnnouncementElement =
			this._resultsRootElement?.querySelector(":scope > #quench-failure-announcement") ?? null;
		this._failureAnnouncementElement?.replaceChildren();
		// @ts-expect-error SearchFilter types have not been updated yet
		this.#searchFilter.bind(this.element);
	}

